from __future__ import annotations
"""
AI content for each relevant article — generated by the configured AI provider
(Hugging Face by default; see llm_client.py), in ONE call:
 
  summary                   - what happened (2-3 factual sentences, no recommendations)
  what_happening            - what is happening
  why_happening             - why it is happening
  why_it_matters_to_mtn     - how / why it relates to MTN Ghana (says so plainly if only indirect)
  impact                    - positive | negative | neutral | mixed
  impact_reason             - why it is good or bad
  outlook                   - what is likely to happen next
  recommended_actions       - [what we should do]  (keep & amplify if positive, stop / contain if negative)
  if_we_act                 - what happens if we do it
  if_we_dont                - what happens if we don't
  confidence                - high | medium | low
  generated_by              - "llm:<model>"
 
There is NO rule-based or template fallback. If the AI cannot produce a valid answer,
generate_ai_content() returns None, nothing is stored, and the item is retried later
(see aisummarizer_service.fill_missing_ai_content). Emails skip items that are not yet analysed.
 
The result is stored once (articles.summary + articles.analysis JSON); the API and emails only read it.
"""
 
import json
import logging
import re
from datetime import datetime
from typing import Any, Optional
 
from . import llm_client
 
logger = logging.getLogger(__name__)
 
ALLOWED_IMPACT = {"positive", "negative", "neutral", "mixed"}
ALLOWED_CONFIDENCE = {"high", "medium", "low"}
 
PENDING_SUMMARY = "AI summary pending…"
 
# Sentences produced by the OLD keyword-template summarizer. Summaries containing any of these
# are treated as generic: hidden from the API and regenerated by the AI.
LEGACY_SUMMARY_FRAGMENTS = (
    "warrants careful compliance oversight",
    "presents an opportunity for mtn ghana to drive high-value",
    "directly influences mtn ghana's mobile money",
    "highlights strong underlying operational performance",
    "bears immediate implications for mtn ghana's network resilience",
    "highlights critical macro-financial exposure",
    "alters the regulatory playing field",
    "highlights infrastructure development and technology optimization",
    "presents operational and commercial risk considerations",
)
 
REQUIRED_TEXT_FIELDS = (
    "what_happening", "why_happening", "why_it_matters_to_mtn",
    "impact_reason", "outlook", "if_we_act", "if_we_dont",
)
 
 
# ── helpers shared with the API / scripts ─────────────────────────────────────
 
def is_usable_summary(text: Any) -> bool:
    """True only for a real AI summary (not empty, not a placeholder, not an old generic template)."""
    s = str(text or "").strip()
    if len(s) < 20:
        return False
    low = s.lower()
    if low in {"summary not available", PENDING_SUMMARY.lower()}:
        return False
    return not any(frag in low for frag in LEGACY_SUMMARY_FRAGMENTS)
 
 
def public_summary(text: Any) -> str:
    """What the API returns: the AI summary, or an honest 'pending' marker. Never generic text."""
    return str(text).strip() if is_usable_summary(text) else PENDING_SUMMARY
 
 
def analysis_to_json(analysis: Optional[dict]) -> Optional[str]:
    if not analysis:
        return None
    return json.dumps(analysis, ensure_ascii=False)
 
 
def parse_analysis(raw: Any) -> Optional[dict]:
    """
    Parse the stored articles.analysis value. Returns None when missing/invalid, and also for
    any legacy rule-based analysis (generated_by == 'rules') so generic text is never shown.
    """
    if not raw:
        return None
    data = raw
    if not isinstance(raw, dict):
        try:
            data = json.loads(raw)
        except Exception:  # noqa: BLE001
            return None
    if not isinstance(data, dict):
        return None
    if str(data.get("generated_by", "")).lower() == "rules":
        return None
    return data
 
 
def _clip(text: Any, limit: int) -> str:
    s = re.sub(r"\s+", " ", str(text or "")).strip()
    if len(s) <= limit:
        return s
    cut = s[:limit].rsplit(" ", 1)[0]
    return cut.rstrip(" ,;:") + "…"
 
 
# ── prompt ────────────────────────────────────────────────────────────────────
 
_SYSTEM_PROMPT = (
    "You are a senior risk analyst at MTN Ghana (Scancom PLC), briefing the Head of Risk and executive "
    "management. MTN Ghana is Ghana's largest mobile operator and runs MTN Mobile Money (MoMo). Key external "
    "parties include the National Communications Authority (NCA), Data Protection Commission, Cyber Security "
    "Authority, Bank of Ghana, Ghana Revenue Authority, Securities and Exchange Commission, National "
    "Identification Authority and the Ministry of Communications.\n\n"
    "For ONE news item you produce (1) a factual summary and (2) the 'SO WHAT?': what management must "
    "understand and do about it.\n\n"
    "RULES\n"
    "- Use ONLY facts stated in the article plus well-established industry knowledge. Never invent numbers, "
    "names, dates, quotes or events.\n"
    "- The summary is 2-3 sentences (max 70 words) of what happened. No advice, no impact commentary.\n"
    "- If the article has little or no direct link to MTN Ghana, say so plainly in why_it_matters_to_mtn, set "
    "impact to 'neutral', and recommend monitoring only. Do not force a link.\n"
    "- Be specific and practical: name the team that should act (e.g. Regulatory Affairs, Fraud, Network, "
    "Treasury, Legal, Corporate Communications, Compliance, MoMo Operations). Avoid vague filler such as "
    "'monitor the situation' unless that is genuinely all that is warranted.\n"
    "- If the impact is positive, the actions explain how to KEEP AND AMPLIFY it. If negative, how to STOP, "
    "CONTAIN or MITIGATE it.\n"
    "- British English. Plain text only: no markdown, no bullet symbols inside strings.\n"
    "- Each analysis text field is 1-3 sentences (max 60 words). recommended_actions has 2-4 short imperative items.\n"
    "- If the article body is missing, work from the headline only and set confidence to 'low'.\n"
    "- Output ONE JSON object and nothing else."
)
 
_JSON_SHAPE = (
    '{"summary": "...", "what_happening": "...", "why_happening": "...", "why_it_matters_to_mtn": "...", '
    '"impact": "positive|negative|neutral|mixed", "impact_reason": "...", "outlook": "...", '
    '"recommended_actions": ["...", "..."], "if_we_act": "...", "if_we_dont": "...", '
    '"confidence": "high|medium|low"}'
)
 
 
def _build_user_prompt(title, body, source_name, category, subcategory, sentiment,
                       severity, alert_tier, mtn_relevance, published_at) -> str:
    pub = ""
    if isinstance(published_at, datetime):
        pub = published_at.strftime("%d %b %Y")
    elif published_at:
        pub = str(published_at)[:10]
 
    facts = [
        f"Headline: {_clip(title, 300)}",
        f"Source: {source_name or 'Unknown'}",
        f"Published: {pub or 'Unknown'}",
        f"Risk category: {category or 'unclassified'}"
        + (f" / {subcategory}" if subcategory and subcategory != "Other" else ""),
        f"Automated sentiment: {sentiment or 'unknown'}",
        f"Automated severity: {severity if severity is not None else 'unknown'} / 10",
        f"Alert tier: {alert_tier or 'none'}",
        f"MTN Ghana relevance score: {round(mtn_relevance * 100) if mtn_relevance is not None else 'unknown'}%",
    ]
    article_text = _clip(body, 6000) or "(No article body available.)"
    return (
        "\n".join(facts)
        + "\n\nArticle text:\n" + article_text
        + "\n\nReturn exactly this JSON shape (all keys required):\n" + _JSON_SHAPE
    )
 
 
# ── parsing / validation ──────────────────────────────────────────────────────
 
def _extract_json(raw: str) -> Optional[dict]:
    if not raw:
        return None
    text = re.sub(r"^```(?:json)?|```$", "", raw.strip(), flags=re.I | re.M).strip()
    start, end = text.find("{"), text.rfind("}")
    if start == -1 or end <= start:
        return None
    try:
        data = json.loads(text[start:end + 1])
    except Exception:  # noqa: BLE001
        return None
    return data if isinstance(data, dict) else None
 
 
def _normalise(data: dict, fallback_sentiment: Optional[str], model_label: str = "") -> Optional[dict]:
    """Validate the AI answer. Returns {'summary': str, 'analysis': dict} or None if incomplete."""
    summary = _clip(data.get("summary"), 700)
    if len(summary) < 25:
        return None
 
    analysis: dict[str, Any] = {}
    for key in REQUIRED_TEXT_FIELDS:
        val = _clip(data.get(key), 500)
        if len(val) < 8:
            return None
        analysis[key] = val
 
    impact = str(data.get("impact") or "").strip().lower()
    if impact not in ALLOWED_IMPACT:
        impact = {"positive": "positive", "negative": "negative"}.get((fallback_sentiment or "").lower(), "neutral")
    analysis["impact"] = impact
 
    actions = data.get("recommended_actions")
    if isinstance(actions, str):
        actions = [a for a in re.split(r"[;\n]+|\s*\d+[.)]\s+", actions) if a.strip()]
    if not isinstance(actions, list):
        return None
    cleaned = [_clip(a, 260) for a in actions if isinstance(a, (str, int, float)) and len(_clip(a, 260)) > 5]
    if not cleaned:
        return None
    analysis["recommended_actions"] = cleaned[:4]
 
    conf = str(data.get("confidence") or "medium").strip().lower()
    analysis["confidence"] = conf if conf in ALLOWED_CONFIDENCE else "medium"
    # "llm:" prefix keeps the email / UI footers saying "AI-assisted analysis"
    analysis["generated_by"] = f"llm:{model_label or 'unknown'}"
 
    return {"summary": summary, "analysis": analysis}
 
 
# ── public API ────────────────────────────────────────────────────────────────
 
def generate_ai_content(
    title: Optional[str],
    body: Optional[str] = "",
    *,
    source_name: Optional[str] = None,
    category: Optional[str] = None,
    subcategory: Optional[str] = None,
    sentiment: Optional[str] = None,
    severity: Optional[float] = None,
    alert_tier: Optional[str] = None,
    mtn_relevance: Optional[float] = None,
    published_at: Any = None,
) -> Optional[dict]:
    """
    Ask the AI for the summary + 'so what' of one article.
 
    Returns {"summary": str, "analysis": dict} or None when the AI is unavailable or the answer
    is unusable (two attempts). Never returns generic placeholder text. Never raises.
    """
    t = str(title or "").strip()
    if not t:
        return None
 
    user_prompt = _build_user_prompt(
        t, str(body or "").strip(), source_name, category, subcategory,
        sentiment, severity, alert_tier, mtn_relevance, published_at,
    )
 
    for attempt in (1, 2):
        try:
            raw, model_label = llm_client.complete(
                _SYSTEM_PROMPT, user_prompt,
                max_tokens=3000, temperature=0.2 if attempt == 1 else 0.0,
            )
        except Exception as exc:  # noqa: BLE001
            logger.warning("AI call raised: %s", exc)
            return None
        if raw is None:
            return None  # every provider unavailable / failed — the caller retries later
        data = _extract_json(raw)
        result = _normalise(data, sentiment, model_label or "") if data else None
        if result:
            return result
        logger.info("AI answer was incomplete or not valid JSON (attempt %d/2) for: %s", attempt, t[:60])
 
    return None
 